const selectedLineId = ref('L7')
const selectedTipoDia = ref('util')
const selectedDirecao = ref('ida') // só para L43

// ─── COMPUTED ────────────────────────────────────────────────

const linha = computed(() => LINHAS[selectedLineId.value])

const isL43 = computed(() => selectedLineId.value === 'L43')

// Horários da seleção atual
const tripsRaw = computed(() => {
  const h = linha.value.horarios
  const key = isL43.value ? selectedTipoDia.value : selectedTipoDia.value
  return h[key] || []
})

// Colunas a mostrar (para L43 depende da direção)
const paragens = computed(() => {
  if (isL43.value) {
    const dir = linha.value.direcoes.find(d => d.id === selectedDirecao.value)
    return dir?.paragens || []
  }
  return linha.value.paragens
})

// Para L43: filtrar colunas relevantes por direção
const trips = computed(() => {
  if (!isL43.value) return tripsRaw.value
  // ida: cols 0,1 | volta: cols 2,3
  const colStart = selectedDirecao.value === 'ida' ? 0 : 2
  return tripsRaw.value
    .map(t => [t[colStart], t[colStart + 1]])
    .filter(t => t[0] !== '--') // só viagens com partida definida
})

// Próxima partida (com base na hora atual)
function timeToMinutes(t) {
  if (!t || t === '--') return Infinity
  const [h, m] = t.split(':').map(Number)
  return h * 60 + m
}

const agora = new Date()
const minutosAgora = agora.getHours() * 60 + agora.getMinutes()

const nextIdx = computed(() => {
  return trips.value.findIndex(t => timeToMinutes(t[0]) >= minutosAgora)
})

const nextTrip = computed(() => nextIdx.value >= 0 ? trips.value[nextIdx.value] : null)

const minutosParaProxima = computed(() => {
  if (!nextTrip.value) return null
  return timeToMinutes(nextTrip.value[0]) - minutosAgora
})

// Mudar de linha
function selectLine(id) {
  selectedLineId.value = id
  // Repor tipo dia para o primeiro disponível
  const l = LINHAS[id]
  selectedTipoDia.value = l.tipoDias[0].id
  selectedDirecao.value = 'ida'
}
